export type Dict = typeof en
export type DictKey = keyof Dict
export const DICT: Dict = en

const numberFormats = new Map<number, Intl.NumberFormat>()

/** A number with a fixed count of decimals, e.g. 1,234.5. */
export function fmt(n: number, digits = 0): string {
  let f = numberFormats.get(digits)
  if (!f) {
    f = new Intl.NumberFormat('en-US', { minimumFractionDigits: digits, maximumFractionDigits: digits })
    numberFormats.set(digits, f)
  }
  return f.format(n)
}

/** A number with significant digits, for tiny values like Bennu's gravity (0.000083). */
export function fmtSig(n: number, significant = 2): string {
  return new Intl.NumberFormat('en-US', { maximumSignificantDigits: significant }).format(n)
}

/** A UI string with its {placeholders} filled. Numbers get up to 2 decimals. */
export function t(key: DictKey, vars?: Record<string, string | number>): string {
  let s: string = en[key]
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      const value = typeof v === 'number' ? fmt(v, Number.isInteger(v) ? 0 : 2) : v
      s = s.replaceAll(`{${k}}`, value)
    }
  }
  return s
}

export const money = (usdM: number): string => t('unit.money', { n: fmt(Math.round(usdM)) })
