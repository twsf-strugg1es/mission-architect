export const DICT: Record<Locale, Dict> = { en, bn }

const numberFormats = new Map<string, Intl.NumberFormat>()

/** Locale-aware number (Bengali digits in bn). */
export function fmt(locale: Locale, n: number, digits = 0): string {
  const key = `${locale}:${digits}`
  let f = numberFormats.get(key)
  if (!f) {
    f = new Intl.NumberFormat(locale === 'bn' ? 'bn-BD' : 'en-US', {
      minimumFractionDigits: digits,
      maximumFractionDigits: digits,
    })
    numberFormats.set(key, f)
  }
  return f.format(n)
}

/** Locale-aware number with significant digits, for tiny values like Bennu's gravity (0.000083). */
export function fmtSig(locale: Locale, n: number, significant = 2): string {
  return new Intl.NumberFormat(locale === 'bn' ? 'bn-BD' : 'en-US', { maximumSignificantDigits: significant }).format(n)
}

/** Translate a UI key, filling {placeholders}. Numbers get up to 2 decimals in the locale's digits. */
export function t(locale: Locale, key: DictKey, vars?: Record<string, string | number>): string {
  let s: string = DICT[locale][key]
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      const value = typeof v === 'number' ? fmt(locale, v, Number.isInteger(v) ? 0 : 2) : v
      s = s.replaceAll(`{${k}}`, value)
    }
  }
  return s
}

/** Pick the locale's side of a JSON {en, bn} text. */
export const tx = (locale: Locale, text: Text): string => text[locale]

export const money = (locale: Locale, usdM: number): string => t(locale, 'unit.money', { n: fmt(locale, Math.round(usdM)) })
